/* Iki dizgi bire bir ayni mi (strcmp yerine) */
static int str_equal(const char *a, const char *b)
{
    while ((*a != '\0') && (*a == *b)) {
        a++;
        b++;
    }
    return (*a == *b) ? 1 : 0;
}

const fs_aging_profile_t *fs_aging_profile_find(const char *name)
{
    uint32_t i;

    if (name == NULL) {
        return NULL;
    }
    for (i = 0u; i < FS_AGING_PROFILE_COUNT; i++) {
        if (str_equal(fs_aging_profiles[i]->name, name) != 0) {
            return fs_aging_profiles[i];
        }
    }
    return NULL;
}
